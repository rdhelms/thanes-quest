// Checks that content is well formed before it is played. Hand-written and generated rooms go
// through the same gate.

import { buildScene } from './build';
import { LAYERS } from './layers';
import { isRamp } from './palette';
import { Parser } from './parser';
import { PROPS } from './props';
import { PH, PW } from './scene';
import { canReach, reachable } from './walk';
import { frontierProblems, roomOf } from './frontier';
import { validateTune } from './tune';
import type { Cond, Content, Effect, RoomDef, Rule, Topic } from './types';

/**
 * Check a whole game's content; or, given `only`, one room against it. The second is the gate a
 * room from anywhere else (written by hand later, or generated by some other means) must pass
 * before it can be let into the world.
 */
export function validate(c: Content, only?: RoomDef): string[] {
  const errs: string[] = [];
  const parser = new Parser(c.vocab);
  for (const r of Object.values(c.rooms)) if (r.vocab) parser.addNouns(r.vocab);

  const noun = (where: string, n: string): void => void (parser.hasNoun(n) || errs.push(`${where}: noun "${n}" is not in the vocabulary`));
  const item = (where: string, id: string): void => void (c.items[id] || errs.push(`${where}: unknown item "${id}"`));
  const room = (where: string, id: string): void => void (roomOf(c, id) || errs.push(`${where}: unknown room "${id}"`));

  const conds = (where: string, list?: Cond[]): void => {
    for (const k of list ?? []) {
      if ('has' in k) item(where, k.has);
      else if ('quest' in k) c.quests[k.quest] || errs.push(`${where}: unknown quest "${k.quest}"`);
      else if ('not' in k) conds(where, [k.not]);
      else if ('any' in k) conds(where, k.any);
    }
  };
  const effects = (where: string, list: Effect[]): void => {
    for (const e of list) {
      if ('note' in e && e.note.length > 80) errs.push(`${where}: the hint "${e.note.slice(0, 24)}..." is over 80 characters and will not fit`);
      else if ('chance' in e) effects(where, e.do);
      else if ('cmd' in e && !parser.parse(e.cmd).ok) errs.push(`${where}: "${e.cmd}" is not a command the parser understands`);
      else if ('give' in e) {
        item(where, e.give);
        if (e.took && e.took.length > 80) errs.push(`${where}: the hint "${e.took.slice(0, 24)}..." is over 80 characters and will not fit`);
      }
      else if ('lose' in e) item(where, e.lose);
      else if ('goto' in e) room(where, e.goto);
      else if ('quest' in e) c.quests[e.quest] || errs.push(`${where}: unknown quest "${e.quest}"`);
      else if ('spawn' in e) c.enemies[e.spawn] || errs.push(`${where}: unknown enemy "${e.spawn}"`);
    }
  };
  const rules = (where: string, list: Rule[] | undefined, r?: RoomDef): void => {
    (list ?? []).forEach((rule, i) => {
      const w = `${where} rule ${i}`;
      if (!rule.on && !rule.enter && !rule.zone && !rule.cleared) errs.push(`${w}: has no trigger`);
      for (const pat of typeof rule.on === 'string' ? [rule.on] : rule.on ?? []) {
        const [verb, ...rest] = pat.split(' ');
        for (const v of verb.split('|')) if (v !== '*' && !parser.hasVerb(v)) errs.push(`${w}: verb "${v}" is not in the vocabulary`);
        for (const part of rest) for (const n of part.split('|')) if (n !== '*') noun(w, n);
      }
      if (rule.zone && !r?.zones?.some((z) => z.id === rule.zone)) errs.push(`${w}: unknown zone "${rule.zone}"`);
      conds(w, rule.if);
      effects(w, rule.do);
    });
  };
  const topic = (where: string, t: Topic): void => {
    if (typeof t === 'string') return;
    for (const b of t) {
      conds(where, b.if);
      if (b.do) effects(where, b.do);
    }
  };

  // One word must not mean two things of the same kind.
  for (const [kind, groups] of [['verb', c.vocab.verbs], ['noun', c.vocab.nouns]] as const) {
    const owner = new Map<string, string>();
    for (const [id, words] of Object.entries(groups))
      for (const w of [id, ...words]) {
        if (owner.has(w) && owner.get(w) !== id) errs.push(`vocabulary: ${kind} "${w}" belongs to both "${owner.get(w)}" and "${id}"`);
        owner.set(w, id);
      }
  }
  for (const s of Object.values(c.spells)) noun(`spell ${s.id}`, s.id);
  for (const w of Object.values(c.words)) parser.hasVerb(w.verb) || errs.push(`runeword ${w.id}: verb "${w.verb}" is not in the vocabulary`);

  for (const t of Object.values(c.music)) errs.push(...validateTune(t));
  for (const [k, id] of Object.entries(c.cues)) c.music[id] || errs.push(`music cue ${k}: unknown tune "${id}"`);

  if (c.tagline.length > 32) errs.push(`the tagline is ${c.tagline.length} characters long, and will not sit on one line`);
  errs.push(...frontierProblems(c));
  room('start', c.start.room);
  rules('global', c.rules);

  for (const ch of Object.values(c.chars)) {
    const w = `character ${ch.id}`;
    ch.nouns.forEach((n) => noun(w, n));
    topic(w, ch.talk);
    for (const m of ch.menu ?? []) {
      conds(`${w} menu`, m.if);
      // A menu row is as wide as the screen allows; anything filled in later is allowed four characters.
      if (m.label.replace(/\{[\w.]+\}/g, '0000').length > 35) errs.push(`${w} menu: "${m.label}" is too long to fit on a row`);
      if (!parser.parse(m.say).ok) errs.push(`${w} menu: "${m.say}" is not a command the parser understands`);
    }
    for (const [k, t] of Object.entries(ch.topics ?? {})) {
      noun(`${w} topic`, k);
      topic(w, t);
    }
  }
  for (const it of Object.values(c.items)) {
    it.nouns.forEach((n) => noun(`item ${it.id}`, n));
    if (!(it.weight >= 0)) errs.push(`item ${it.id}: has no weight`);
    // What a story needs can never be left behind, so it must never be what fills a pack.
    if (it.keep && it.weight !== 0) errs.push(`item ${it.id}: is kept for a story, and so must weigh nothing`);
    if (it.carry && !it.keep) errs.push(`item ${it.id}: carries more, and so must be kept: dropping it would leave a pack over-full`);
    if (it.use) effects(`item ${it.id}`, it.use);
  }
  for (const en of Object.values(c.enemies)) en.nouns.forEach((n) => noun(`enemy ${en.id}`, n));

  const opposite = { n: 's', s: 'n', e: 'w', w: 'e' } as const;
  const checkRoom = (r: RoomDef): void => {
    const w = `room ${r.id}`;
    const def = r.scene;
    if (r.music && !c.music[r.music]) errs.push(`${w}: unknown tune "${r.music}"`);
    for (const l of def.layers) LAYERS[l.t] || errs.push(`${w}: unknown layer "${l.t}"`);
    for (const p of [...def.props, ...(def.when ?? []).flatMap((v) => v.props ?? [])]) {
      const impl = PROPS[p.t];
      if (!impl) {
        errs.push(`${w}: unknown prop "${p.t}"`);
        continue;
      }
      for (const k of impl.needs ?? []) if (p[k] === undefined) errs.push(`${w}: prop "${p.t}" needs "${k}"`);
      if (p.ramp && !isRamp(p.ramp)) errs.push(`${w}: unknown material "${p.ramp}"`);
    }

    for (const [side, to] of Object.entries(r.exits ?? {}) as ['n' | 's' | 'e' | 'w', string][]) {
      room(`${w} exit ${side}`, to);
      if (roomOf(c, to) && roomOf(c, to)!.exits?.[opposite[side]] !== r.id) errs.push(`${w}: exit ${side} to "${to}" has no way back`);
    }
    const ids = new Set<string>();
    if ((r.things ?? []).filter((t) => t.store).length > 1) errs.push(`${w}: has more than one store; a room keeps one`);
    for (const t of r.things ?? []) {
      if (ids.has(t.id)) errs.push(`${w}: duplicate thing "${t.id}"`);
      ids.add(t.id);
      t.nouns.forEach((n) => noun(`${w} thing ${t.id}`, n));
      if (t.take) item(`${w} thing ${t.id}`, t.take);
      for (const line of t.try ?? []) if (!parser.parse(line).ok) errs.push(`${w} thing ${t.id}: "${line}" is not a command the parser understands`);
    }
    for (const n of r.npcs ?? []) {
      c.chars[n.char] || errs.push(`${w}: unknown character "${n.char}"`);
      conds(w, n.if);
    }
    for (const s of r.spawns ?? []) c.enemies[s.kind] || errs.push(`${w}: unknown enemy "${s.kind}"`);
    for (const d of r.doors ?? []) {
      room(`${w} door`, d.to);
      conds(`${w} door`, d.if);
    }
    rules(w, r.rules, r);

    // Geometry: can the player actually get to everything?
    const sc = buildScene(def);
    const mid = Math.round((def.walkTop + PH) / 2);
    const from = r.id === c.start.room ? [c.start.x, c.start.y] : [PW / 2, mid];
    const seen = reachable(sc, from[0], from[1]);
    if (!seen.some((v) => v)) {
      errs.push(`${w}: has no walkable ground`);
      return;
    }
    const col = (x: number): boolean => {
      for (let y = def.walkTop; y < PH; y++) if (seen[y * PW + x]) return true;
      return false;
    };
    const row = (y: number): boolean => {
      for (let x = 0; x < PW; x++) if (seen[y * PW + x]) return true;
      return false;
    };
    if (r.exits?.w && !col(7)) errs.push(`${w}: west edge cannot be reached`);
    if (r.exits?.e && !col(PW - 8)) errs.push(`${w}: east edge cannot be reached`);
    if (r.exits?.n && !row(def.walkTop + 1)) errs.push(`${w}: north edge cannot be reached`);
    if (r.exits?.s && !row(PH - 3)) errs.push(`${w}: south edge cannot be reached`);
    for (const t of r.things ?? []) if (!canReach(seen, t.x, t.y, t.reach ?? 30)) errs.push(`${w}: thing "${t.id}" cannot be reached`);
    for (const n of r.npcs ?? []) if (!canReach(seen, n.x, n.y, 48)) errs.push(`${w}: character "${n.char}" cannot be reached`);
    for (const d of r.doors ?? [])
      if (!canReach(seen, (d.x0 + d.x1) / 2, (d.y0 + d.y1) / 2, 6)) errs.push(`${w}: door to "${d.to}" cannot be reached`);
  };
  if (only) checkRoom(only);
  // With any gates onto the frontier added, as the game will see it.
  else for (const hand of Object.values(c.rooms)) checkRoom(roomOf(c, hand.id)!);
  return errs;
}
